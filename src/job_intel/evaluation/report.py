"""Render reports/evaluation_report.md from the benchmark JSON files (no number is typed by hand)."""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

REPORTS = Path(__file__).resolve().parents[3] / "reports"


def _load(name: str):
    p = REPORTS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _f(x, nd: int = 3) -> str:
    return "–" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def _table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(_f(c) if not isinstance(c, str) else c for c in r) + " |" for r in rows]
    return "\n".join(out)


def build() -> str:
    parts = [f"# Evaluation report\n\n*Generated by `jobintel bench all` on {date.today().isoformat()} from `reports/*.json`. "
             "Every number below comes from those files.*\n"]  # fmt: skip
    parts.append("## How to read this report\n\n"
                 "* **Labels.** No human has graded these results yet. Relevance grades and gold skills were written by the AI "
                 "assistant that built the system, blind to system outputs, with written rubrics. That is a conflict of "
                 "interest; the numbers are *indicative* and the tooling accepts human grades (they take precedence automatically).\n"
                 "* **Small samples.** 10 retrieval queries, 3 synthetic candidates, 20+12 annotated listings, 26 assistant "
                 "questions. Confidence intervals are wide on purpose: they are honest.\n"
                 "* **No significance theatre.** Paired bootstrap p-values are reported for retrieval only, as a descriptive aid.\n")  # fmt: skip
    r = _load("retrieval_benchmark.json")
    if r:
        rows = []
        for name, s in r["systems"].items():
            rows.append([name] + [f"{s[m]['mean']:.3f} [{s[m]['ci_low']:.2f}, {s[m]['ci_high']:.2f}]" for m in ("ndcg@10", "p@5", "map@10", "recall@10")]
                        + [f"{s['mrr@10_strict']['mean']:.3f}", f"{s['judged@10']['mean']:.2f}", f"{s['latency_ms']['p50']:.0f}"])  # fmt: skip
        paired = [[k, _f(v["mean_diff"]), f"{v['wins']}/{v['ties']}/{v['losses']}", _f(v["paired_bootstrap_p"])] for k, v in r["paired_vs_bm25_ndcg@10"].items()]
        parts.append(f"## 1. Retrieval: five systems\n\n{r['label_note']}\n\nCorpus: {r['corpus']}; {r['n_queries']} queries; "
                     f"{r['n_judgments']} graded (query, job) pairs, pooled from every system's top 10.\n\n"
                     + _table(["system", "nDCG@10 [95% CI]", "P@5", "MAP@10", "recall@10 (pooled)", "MRR@10 (grade 2)", "judged@10", "latency p50 (ms)"], rows)
                     + "\n\nPaired comparison with BM25 on nDCG@10 (per-query wins/ties/losses):\n\n"
                     + _table(["comparison", "mean difference", "W/T/L", "paired bootstrap p"], paired)
                     + "\n\n*MRR@10 with grade ≥ 1 is 1.0 for almost every system (the first result is nearly always at least partly "
                       "relevant), so the strict version (grade 2) is shown.*\n")  # fmt: skip
    s = _load("skills_benchmark.json")
    if s:
        rows = [["held-out test (after fixes)", s["n_docs"], s["n_gold"], s["micro"]["precision"], s["micro"]["recall"], s["micro"]["f1"], s["in_vocabulary_recall"]]]
        if "dev_before_fixes" in s:
            d = s["dev_before_fixes"]
            rows.insert(0, ["dev, before error analysis", d["n_docs"], d["n_gold"], d["micro"]["precision"], d["micro"]["recall"], d["micro"]["f1"], d["in_vocabulary_recall"]])
        d = s["dev_after_fixes"]
        rows.insert(1, ["dev, after fixes (optimistic)", d["n_docs"], d["n_gold"], d["micro"]["precision"], d["micro"]["recall"], d["micro"]["f1"], d["in_vocabulary_recall"]])
        parts.append("## 2. Skill extraction from listings\n\n" + s["label_note"] + "\n\n"
                     + _table(["set", "listings", "gold skills", "precision", "recall", "F1 (micro)", "in-vocabulary recall"], rows)
                     + f"\n\nOn the test set {s['oov_share_of_gold']:.0%} of the gold skills are outside the taxonomy (e.g. "
                     f"{', '.join(x[0].removeprefix('OOV:') for x in s['errors']['false_negatives'] if x[0].startswith('OOV:'))[:160]}…): "
                     "a dictionary extractor cannot find them, which is the main recall limit.\n\n"
                     f"Sector heuristic on the test listings: accuracy {_f(s['sector']['accuracy'], 2)} where it predicts, coverage "
                     f"{_f(s['sector']['coverage'], 2)} - too weak to rely on; the UI labels it an estimate.\n")  # fmt: skip
    c = _load("scoring_calibration.json")
    if c:
        rows = [[k, v["mean_ndcg@10"]] + [v.get(f"ndcg_{cid}") for cid in c["candidates"]] for k, v in c["methods"].items()]
        e = c["eligibility_agreement"]
        parts.append("## 3. Matching: ranking a candidate's eligible jobs\n\n" + c["label_note"] + "\n\n"
                     + _table(["ordering", "mean nDCG@10"] + c["candidates"], rows)
                     + f"\n\n**Conclusion.** {c['conclusion']}\n\n"
                     f"**Eliminatory constraints vs labels:** precision of exclusions {_f(e['precision_of_exclusions'], 2)} "
                     f"({e['excluded_and_labelled_ineligible']} excluded and labelled ineligible, {e['excluded_but_labelled_eligible']} "
                     f"wrongly excluded), recall {_f(e['recall_of_exclusions'], 2)} ({e['kept_but_labelled_ineligible']} ineligible jobs "
                     "kept - mostly constraints stated only in free text, e.g. 'freelance position', which the system treats as unknown).\n")  # fmt: skip
    a = _load("assistant_benchmark.json")
    if a:
        keys = ["routing_accuracy", "citation_validity", "faithfulness", "hallucination_rate", "fallback_rate", "answer_relevance",
                "retrieval_relevance", "forbidden_claims_in_final", "latency_median_s", "est_llm_tokens_per_question"]  # fmt: skip
        rows = [[m] + [v.get(k) for k in keys] for m, v in a["modes"].items()]
        parts.append("## 4. Career assistant (RAG)\n\n" + a["label_note"] + "\n\n" + _table(["mode"] + keys, rows)
                     + "\n\n*faithfulness / hallucination rate are measured on the sentences PROPOSED by the generator, before the "
                       "verifier removes unsupported ones; what the user sees has passed the verifier. The verifier checks named "
                       "entities, numbers, credentials and topical overlap - not the truth of qualitative statements.*\n")  # fmt: skip
    lat = _load("latency.json")
    if lat:
        rows = [[k, v.get("median_ms", v.get("ms")), v.get("p95_ms", "–")] for k, v in lat["steps"].items()]
        vb = lat["vector_backends"]
        parts.append("## 5. Latency and resources\n\n" + f"Hardware: {lat['hardware']}\n\n" + _table(["step", "median / single (ms)", "p95 (ms)"], rows)
                     + f"\n\nVector search: FAISS exact {vb['faiss_flat_ms_median']} ms vs Chroma HNSW {vb['chroma_hnsw_ms_median']} ms per "
                     f"query; HNSW recall@10 against the exact search = {vb['hnsw_recall@10_vs_exact']}.\n\n"
                     f"Resources: {json.dumps(lat['resources'])}\n\nLLM cost: {lat['llm_cost']}.\n")  # fmt: skip
    parts.append("## Known biases and limits\n\n"
                 "* **Pool bias.** The original retrieval pool came from BM25, dense and hybrid; keyword and re-rank results were "
                 "judged afterwards for the gaps (see judged@10).\n"
                 "* **Corpus.** Three job boards, data/AI titles only; Himalayas is remote-only and US-heavy; the frozen evaluation "
                 "corpus is Arbeitnow only (Germany/Netherlands/France heavy). Results may not transfer to other markets.\n"
                 "* **Synthetic CVs.** Three invented candidates; real CVs have messier layouts (the parser is rule-based).\n"
                 "* **Same author.** System, labels and rubrics come from the same assistant: human review of "
                 "`data/eval/proposals/*` is the next step (`jobintel label …` tools exist).\n")  # fmt: skip
    return "\n".join(parts)


def write_markdown() -> Path:
    path = REPORTS / "evaluation_report.md"
    path.write_text(build(), encoding="utf-8")
    return path
